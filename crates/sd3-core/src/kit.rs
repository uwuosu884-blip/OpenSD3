//! Unified drum-kit manifest (`kit.json`) + `.sfz` importer and exporter.
//!
//! Models multi-pad drums with:
//! - Standard GM / Superior Drummer 3 MIDI key mappings
//! - Choke / mute groups (e.g., closed/pedal hi-hat chokes open hi-hat)
//! - Multi-velocity layers (`lovel..=hivel`)
//! - Round-robin variations (`rr_index`)
//! - Discrete microphone buses (`Close`, `OH`, `Room`, `Bleed`) per hit!

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::{Result, Sd3Error};

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum MicBus {
    Close,
    Oh,
    Room,
    Bleed,
}

impl MicBus {
    pub const ALL: [MicBus; 4] = [MicBus::Close, MicBus::Oh, MicBus::Room, MicBus::Bleed];

    #[inline]
    pub fn index(&self) -> usize {
        match self {
            MicBus::Close => 0,
            MicBus::Oh => 1,
            MicBus::Room => 2,
            MicBus::Bleed => 3,
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            MicBus::Close => "close",
            MicBus::Oh => "oh",
            MicBus::Room => "room",
            MicBus::Bleed => "bleed",
        }
    }

    pub fn from_name(s: &str) -> Self {
        let lower = s.to_ascii_lowercase();
        if lower.contains("oh") || lower.contains("overhead") {
            MicBus::Oh
        } else if lower.contains("room") || lower.contains("amb") {
            MicBus::Room
        } else if lower.contains("bleed") {
            MicBus::Bleed
        } else {
            MicBus::Close
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DrumKitManifest {
    pub name: String,
    pub source_format: String,
    pub sample_rate: u32,
    pub pads: Vec<PadSpec>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PadSpec {
    pub id: String,
    pub name: String,
    /// Primary MIDI note + any SD3 alias notes that trigger this articulation.
    pub midi_notes: Vec<u8>,
    /// Optional mute/choke group (e.g. `1` for hi-hats or cymbal mute trigger).
    pub group: Option<u32>,
    /// Optional group choked when that group triggers (e.g. open hat or sustain cymbal sets `off_by_this = Some(1)`).
    pub off_by_this: Option<u32>,
    /// Optional hi-hat openness (`0` = tight closed .. `127` = wide open) for MIDI CC4 selection.
    #[serde(default)]
    pub hihat_openness: Option<u8>,
    /// True when velocity layers already capture natural acoustic loudness (`RIFF 'ttbw'` recordings).
    #[serde(default)]
    pub natural_vel_dynamics: bool,
    pub layers: Vec<VelocityLayerSpec>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VelocityLayerSpec {
    pub lovel: u8,
    pub hivel: u8,
    /// Round-robin variations; each variation maps a `MicBus` to a relative WAV path.
    pub round_robins: Vec<RoundRobinSample>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RoundRobinSample {
    pub rr_index: usize,
    pub mic_files: BTreeMap<MicBus, String>,
}

impl DrumKitManifest {
    pub fn load_json(path: impl AsRef<Path>) -> Result<Self> {
        let text = fs::read_to_string(path)?;
        Ok(serde_json::from_str(&text)?)
    }

    pub fn save_json(&self, path: impl AsRef<Path>) -> Result<()> {
        if let Some(p) = path.as_ref().parent() {
            fs::create_dir_all(p)?;
        }
        let text = serde_json::to_string_pretty(self)?;
        fs::write(path, text)?;
        Ok(())
    }

    /// Export an SFZ 2.0 instrument file compatible with `sfizz`, `LinuxSampler`, and `Sforzando`.
    /// If `mic_filter` is `None`, emits layered regions for all mic buses with volume controls.
    pub fn to_sfz(&self, mic_filter: Option<MicBus>) -> String {
        let mut out = String::new();
        out.push_str(&format!("// Generated by open-sd3 for kit: {}\n", self.name));
        out.push_str("<control>\ndefault_path=\n\n");
        out.push_str("<global>\nloop_mode=one_shot\nampeg_release=0.25\n\n");

        for pad in &self.pads {
            let Some(&primary_note) = pad.midi_notes.first() else {
                continue;
            };
            out.push_str(&format!("// === {} (MIDI {:?}) ===\n", pad.name, pad.midi_notes));
            for &note in &pad.midi_notes {
                out.push_str("<group>");
                out.push_str(&format!(" key={note}"));
                if let Some(g) = pad.group {
                    out.push_str(&format!(" group={g}"));
                }
                if let Some(off) = pad.off_by_this {
                    // In SFZ, `off_by=N` sits on the Victim group (open hat) choked by group N!
                    // Our `PadSpec` tracks both `group` and `off_by_this`; open hat sets `group=2, off_by_this=Some(1)` -> `off_by=1`.
                    if off != pad.group.unwrap_or(0) {
                        out.push_str(&format!(" off_by={off} off_mode=fast"));
                    }
                }
                let _ = primary_note;
                out.push('\n');

                for layer in &pad.layers {
                    let seq_len = layer.round_robins.len().max(1);
                    for (idx, rr) in layer.round_robins.iter().enumerate() {
                        for (&bus, rel_path) in &rr.mic_files {
                            if let Some(only) = mic_filter {
                                if bus != only {
                                    continue;
                                }
                            }
                            let vol_db = match bus {
                                MicBus::Close => 0.0,
                                MicBus::Oh => -3.0,
                                MicBus::Room => -6.0,
                                MicBus::Bleed => -12.0,
                            };
                            out.push_str(&format!(
                                "<region> sample={} lovel={} hivel={} seq_length={} seq_position={} volume={:.1}\n",
                                rel_path.replace('\\', "/"),
                                layer.lovel,
                                layer.hivel,
                                seq_len,
                                idx + 1,
                                vol_db
                            ));
                        }
                    }
                }
                out.push('\n');
            }
        }
        out
    }

    /// Minimal SFZ importer so `open-sd3` can also load standard `.sfz` drum kits directly.
    pub fn from_sfz_file(sfz_path: impl AsRef<Path>) -> Result<(Self, PathBuf)> {
        let sfz_path = sfz_path.as_ref();
        let base_dir = sfz_path
            .parent()
            .unwrap_or_else(|| Path::new("."))
            .to_path_buf();
        let content = fs::read_to_string(sfz_path)?;

        let mut default_prefix = String::new();
        let mut group_opcodes: BTreeMap<String, String> = BTreeMap::new();
        let mut global_opcodes: BTreeMap<String, String> = BTreeMap::new();
        let mut pads_by_note: BTreeMap<u8, PadSpec> = BTreeMap::new();

        for raw_line in content.lines() {
            let line = raw_line.split("//").next().unwrap_or("").trim();
            if line.is_empty() {
                continue;
            }
            let mut rest = line;
            while let Some(tag_start) = rest.find('<') {
                let Some(tag_end) = rest[tag_start..].find('>') else {
                    break;
                };
                let tag = &rest[tag_start + 1..tag_start + tag_end];
                let after_tag = &rest[tag_start + tag_end + 1..];
                let next_tag = after_tag.find('<').unwrap_or(after_tag.len());
                let body = after_tag[..next_tag].trim();
                let ops = parse_sfz_opcodes(body);

                match tag {
                    "control" => {
                        if let Some(dp) = ops.get("default_path") {
                            default_prefix = dp.clone();
                        }
                    }
                    "global" => {
                        global_opcodes = ops;
                    }
                    "group" => {
                        group_opcodes = global_opcodes.clone();
                        for (k, v) in ops {
                            group_opcodes.insert(k, v);
                        }
                    }
                    "region" => {
                        let mut merged = group_opcodes.clone();
                        for (k, v) in ops {
                            merged.insert(k, v);
                        }
                        if let Some(sample_rel) = merged.get("sample") {
                            let note = merged
                                .get("key")
                                .or_else(|| merged.get("pitch_keycenter"))
                                .or_else(|| merged.get("lokey"))
                                .and_then(|s| parse_midi_note(s))
                                .unwrap_or(36);
                            let lovel = merged
                                .get("lovel")
                                .and_then(|s| s.parse::<u8>().ok())
                                .unwrap_or(1);
                            let hivel = merged
                                .get("hivel")
                                .and_then(|s| s.parse::<u8>().ok())
                                .unwrap_or(127);
                            let group = merged.get("group").and_then(|s| s.parse::<u32>().ok());
                            let off_by = merged.get("off_by").and_then(|s| s.parse::<u32>().ok());
                            let full_rel = format!("{default_prefix}{sample_rel}");
                            let bus = MicBus::from_name(&full_rel);

                            let pad = pads_by_note.entry(note).or_insert_with(|| PadSpec {
                                id: format!("note_{note}"),
                                name: gm_drum_name(note).to_owned(),
                                midi_notes: vec![note],
                                group,
                                off_by_this: off_by,
                                hihat_openness: None,
                                natural_vel_dynamics: false,
                                layers: Vec::new(),
                            });
                            let layer = match pad
                                .layers
                                .iter_mut()
                                .find(|l| l.lovel == lovel && l.hivel == hivel)
                            {
                                Some(l) => l,
                                None => {
                                    pad.layers.push(VelocityLayerSpec {
                                        lovel,
                                        hivel,
                                        round_robins: Vec::new(),
                                    });
                                    pad.layers.last_mut().unwrap()
                                }
                            };
                            let seq_pos = merged
                                .get("seq_position")
                                .and_then(|s| s.parse::<usize>().ok())
                                .unwrap_or(layer.round_robins.len() + 1)
                                .saturating_sub(1);
                            if let Some(rr) =
                                layer.round_robins.iter_mut().find(|r| r.rr_index == seq_pos)
                            {
                                rr.mic_files.insert(bus, full_rel);
                            } else {
                                let mut mic_files = BTreeMap::new();
                                mic_files.insert(bus, full_rel);
                                layer.round_robins.push(RoundRobinSample {
                                    rr_index: seq_pos,
                                    mic_files,
                                });
                            }
                        }
                    }
                    _ => {}
                }
                rest = &after_tag[next_tag..];
            }
        }

        if pads_by_note.is_empty() {
            return Err(Sd3Error::Format("no playable <region> entries found in SFZ".into()));
        }

        let name = sfz_path
            .file_stem()
            .map(|s| s.to_string_lossy().into_owned())
            .unwrap_or_else(|| "SFZ Kit".into());

        Ok((
            DrumKitManifest {
                name,
                source_format: "sfz".into(),
                sample_rate: 44_100,
                pads: pads_by_note.into_values().collect(),
            },
            base_dir,
        ))
    }
}

fn parse_sfz_opcodes(body: &str) -> BTreeMap<String, String> {
    let mut map = BTreeMap::new();
    // Handle `sample=path with spaces.wav` by scanning `key=` positions.
    let mut eq_positions = Vec::new();
    let bytes = body.as_bytes();
    for (idx, &b) in bytes.iter().enumerate() {
        if b == b'=' {
            let mut ks = idx;
            while ks > 0 && !bytes[ks - 1].is_ascii_whitespace() {
                ks -= 1;
            }
            if ks < idx {
                eq_positions.push((ks, idx));
            }
        }
    }
    for (i, &(ks, eq)) in eq_positions.iter().enumerate() {
        let key = body[ks..eq].trim().to_ascii_lowercase();
        let val_end = eq_positions
            .get(i + 1)
            .map(|&(next_ks, _)| next_ks)
            .unwrap_or(body.len());
        let val = body[eq + 1..val_end].trim().to_owned();
        map.insert(key, val);
    }
    map
}

fn parse_midi_note(s: &str) -> Option<u8> {
    if let Ok(n) = s.parse::<u8>() {
        return Some(n.min(127));
    }
    let s = s.trim();
    if s.len() < 2 {
        return None;
    }
    let (note_part, oct_part) = if s.as_bytes().get(1) == Some(&b'#') {
        (&s[..2], &s[2..])
    } else {
        (&s[..1], &s[1..])
    };
    let semitone: i32 = match note_part.to_ascii_uppercase().as_str() {
        "C" => 0,
        "C#" => 1,
        "D" => 2,
        "D#" => 3,
        "E" => 4,
        "F" => 5,
        "F#" => 6,
        "G" => 7,
        "G#" => 8,
        "A" => 9,
        "A#" => 10,
        "B" => 11,
        _ => return None,
    };
    let oct: i32 = oct_part.parse().ok()?;
    let midi = (oct + 1) * 12 + semitone;
    (0..=127).contains(&midi).then_some(midi as u8)
}

pub fn gm_drum_name(note: u8) -> &'static str {
    match note {
        35 | 36 => "Kick",
        37 => "Sidestick",
        38 => "Snare Center",
        39 => "Hand Clap",
        40 => "Snare Rimshot",
        41 | 43 => "Floor Tom",
        42 | 22 => "Hi-Hat Closed",
        44 => "Hi-Hat Pedal",
        45 | 47 => "Mid Tom",
        46 | 26 => "Hi-Hat Open",
        48 | 50 => "High Tom",
        49 => "Crash 1",
        51 => "Ride Bow",
        52 => "China",
        53 => "Ride Bell",
        55 => "Splash",
        57 => "Crash 2",
        59 => "Ride Edge",
        _ => "Drum Pad",
    }
}
